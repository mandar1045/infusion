defmodule Infusion.Gen.Project do
  @moduledoc """
  Generates the files around the API modules: the client module, `mix.exs`,
  `.formatter.exs`, `.gitignore` and a README.
  """

  alias Infusion.IR
  alias Infusion.Gen.{Operations, Source}
  alias Infusion.Naming

  @runtime_version "~> 0.1"

  @doc """
  Options:

    * `:app`: the OTP app (default: `<name>_sdk`, e.g. `:openai_sdk`)
    * `:version`: the SDK's version (default `"0.1.0"`)
    * `:env_var`: where the API key is read from (default `OPENAI_API_KEY`)
    * `:runtime_dep`: the `infusion_runtime` dependency as code (default
      `{:infusion_runtime, "~> 0.1"}`), e.g. a `path:` dependency
  """
  @spec render(%IR{}, String.t(), map, keyword) :: [Infusion.Gen.Schemas.file()]
  def render(%IR{} = ir, base, document, opts \\ []) do
    snake = Naming.package(base)
    app = Keyword.get(opts, :app, String.to_atom(snake <> "_sdk"))
    version = Keyword.get(opts, :version, "0.1.0")
    env_var = Keyword.get(opts, :env_var, String.upcase(snake) <> "_API_KEY")

    runtime_dep =
      Keyword.get(opts, :runtime_dep, "{:infusion_runtime, #{inspect(@runtime_version)}}")

    info = document["info"] || %{}
    title = info["title"] || base

    [
      %{
        module: base,
        path: "lib/#{snake}.ex",
        source: client(ir, base, app, version, env_var, title, info)
      },
      %{module: nil, path: "mix.exs", source: mix_exs(base, app, version, runtime_dep, title)},
      %{
        module: nil,
        path: ".formatter.exs",
        source: ~s([inputs: ["{mix,.formatter}.exs", "{config,lib,test}/**/*.{ex,exs}"]]\n)
      },
      %{
        module: nil,
        path: ".gitignore",
        source: "/_build/\n/deps/\n/doc/\nerl_crash.dump\n*.ez\n"
      },
      %{module: nil, path: "README.md", source: readme(ir, base, app, version, env_var, title)}
    ]
  end

  defp client(ir, base, app, version, env_var, title, info) do
    defaults =
      [
        base_url: Operations.server_url(List.first(ir.servers)),
        api_key: if(ir.auth, do: {:env, env_var}),
        auth: ir.auth,
        user_agent: "#{app}/#{version} (Elixir; infusion_runtime)"
      ]
      |> Enum.reject(fn {_k, v} -> v == nil end)

    """
    defmodule #{base} do
      @moduledoc #{Source.doc(moduledoc(base, app, env_var, title, info, ir))}

      @defaults #{lit(defaults)}

      @doc \"\"\"
      The settings for a call: the defaults, then `config :#{app}, ...`, then
      `opts`. See `Infusion.Runtime.Config` for every setting.
      \"\"\"
      @spec config(keyword) :: Infusion.Runtime.Config.t()
      def config(opts \\\\ []) do
        Infusion.Runtime.Config.new([@defaults, Application.get_all_env(#{inspect(app)}), opts])
      end

      @doc \"\"\"
      Calls an endpoint this SDK has no function for:

          #{base}.request(:get, "/some/path", %{"limit" => 10})

      `params` go into the query for GET and DELETE, into a JSON body otherwise.
      \"\"\"
      @spec request(atom, String.t(), map | keyword, keyword) ::
              {:ok, term} | {:error, Infusion.Runtime.Error.t()}
      def request(method, path, params \\\\ %{}, opts \\\\ []) do
        operation = %{
          id: nil,
          method: method,
          path: path,
          body: if(method in [:get, :head, :delete], do: nil, else: :json)
        }

        __request__(operation, [], params, opts)
      end

      @doc false
      def __request__(operation, path_args, params, opts) do
        Infusion.Runtime.Request.run(config(), operation, path_args, params, opts)
      end

      @doc false
      def __stream__(operation, path_args, params, opts) do
        Infusion.Runtime.Request.stream(config(), operation, path_args, params, opts)
      end
    end
    """
    |> format()
  end

  defp moduledoc(base, app, env_var, title, info, ir) do
    description = String.trim(info["description"] || "")

    auth =
      if ir.auth,
        do: "The API key is read from `#{env_var}`, or set it in your config:",
        else: "Settings go in your config:"

    """
    Elixir SDK for #{title}#{if info["version"], do: " (API version #{info["version"]})", else: ""}.

    #{description}

    ## Configuration

    #{auth}

        config :#{app}, api_key: "...", max_retries: 3, timeout: 60_000

    Any setting can also be given to a single call, as the last argument:

        #{base}.SomeResource.some_call(params, timeout: 5_000)

    Generated by [Infusion](https://github.com/mandar1045/infusion).
    """
    |> String.replace(~r/\n{3,}/, "\n\n")
  end

  defp mix_exs(base, app, version, runtime_dep, title) do
    """
    defmodule #{base}.MixProject do
      use Mix.Project

      def project do
        [
          app: #{inspect(app)},
          version: #{inspect(version)},
          elixir: "~> 1.18",
          start_permanent: Mix.env() == :prod,
          deps: deps(),
          description: #{inspect("Elixir SDK for #{title}, generated by Infusion")}
        ]
      end

      def application do
        [extra_applications: [:logger]]
      end

      defp deps do
        [
          #{runtime_dep},
          {:plug, "~> 1.14", only: :test},
          {:ex_doc, "~> 0.34", only: :dev, runtime: false}
        ]
      end
    end
    """
    |> format()
  end

  defp readme(ir, base, app, version, env_var, title) do
    """
    # #{base}

    Elixir SDK for #{title}, generated from its OpenAPI spec by
    [Infusion](https://github.com/mandar1045/infusion).

    ```elixir
    def deps do
      [{#{inspect(app)}, "~> #{version |> String.split(".") |> Enum.take(2) |> Enum.join(".")}"}]
    end
    ```

    #{if ir.auth, do: "Set `#{env_var}`, or `config :#{app}, api_key: \"...\"`.", else: ""}

    Every call returns `{:ok, result}` or `{:error, %Infusion.Runtime.Error{}}`,
    and has a `!` variant that raises. Calls are retried on connection errors,
    429 and 5xx, as the official SDKs do.

    #{length(ir.operations)} operations, #{map_size(ir.schemas)} schemas.
    """
    |> String.replace(~r/\n{3,}/, "\n\n")
  end

  defp lit(term), do: Source.lit(term)
  defp format(source), do: Source.format(source)
end
