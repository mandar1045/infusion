defmodule Infusion.Gen.Project do
  @moduledoc """
  Generates the files around the API modules: the client module, `mix.exs`,
  `.formatter.exs`, `.gitignore`, a README, and GitHub workflows: CI, and,
  when the spec is a URL, a scheduled regeneration that opens a pull request
  when the spec changes.
  """

  alias Infusion.IR
  alias Infusion.Gen.{Operations, Source}
  alias Infusion.Naming

  # ~> 0.1.0, not ~> 0.1: before 1.0, a minor release may break SDKs.
  @runtime_version "~> 0.2.0"

  # The SDK regenerates itself (`mix infusion.gen` in its directory, and the
  # scheduled workflow) with this generator, pinned to its minor version:
  # a newer minor may rename functions, which should be a deliberate upgrade.
  @infusion_version Mix.Project.config()[:version]
  @infusion_requirement "~> " <>
                          (@infusion_version
                           |> String.split(".")
                           |> Enum.take(2)
                           |> Enum.join(".")) <> ".0"

  @doc """
  Options:

    * `:app`: the OTP app (default: `<name>_sdk`, e.g. `:openai_sdk`)
    * `:version`: the SDK's version (default `"0.1.0"`)
    * `:license`: the SDK's license for Hex (default `"Apache-2.0"`)
    * `:env_var`: where the API key is read from (default `OPENAI_API_KEY`)
    * `:runtime_dep`: the `infusion_runtime` dependency as code (default
      `{:infusion_runtime, "~> 0.2.0"}`), e.g. a `path:` dependency
    * `:infusion_dep`: the same for `infusion` itself, a dev-only dependency
      so the SDK can regenerate itself
    * `:spec`, `:out`: where the spec is and where the SDK goes, for the
      generated `infusion.exs`
    * the client settings of `Infusion.Config` (`headers`, `timeout`, ...),
      which become the client's defaults
  """
  @spec render(%IR{}, String.t(), map, keyword) :: [Infusion.Gen.Schemas.file()]
  def render(%IR{} = ir, base, document, opts \\ []) do
    snake = Naming.package(base)
    app = Keyword.get(opts, :app, String.to_atom(snake <> "_sdk"))
    version = Keyword.get(opts, :version, "0.1.0")
    env_var = Keyword.get(opts, :env_var, String.upcase(snake) <> "_API_KEY")

    runtime_dep =
      Keyword.get(opts, :runtime_dep, "{:infusion_runtime, #{inspect(@runtime_version)}}")

    infusion_dep =
      Keyword.get(opts, :infusion_dep, "{:infusion, #{inspect(@infusion_requirement)}") <>
        ", only: :dev, runtime: false}"

    info = document["info"] || %{}
    title = info["title"] || base

    [
      %{
        module: base,
        path: "lib/#{snake}.ex",
        source: client(ir, base, app, version, env_var, title, info, opts)
      },
      %{module: nil, path: "infusion.exs", source: infusion_exs(base, app, env_var, opts)},
      %{
        module: nil,
        path: "mix.exs",
        source:
          mix_exs(
            base,
            app,
            version,
            [runtime_dep, infusion_dep],
            opts[:description] || "Elixir SDK for #{title}, generated by Infusion",
            Keyword.get(opts, :license, "Apache-2.0"),
            opts[:links] || %{},
            # A changelog the author keeps goes into the docs too.
            ["README.md"] ++ Enum.filter(opts[:keep] || [], &(&1 == "CHANGELOG.md"))
          )
      },
      %{
        module: nil,
        path: ".formatter.exs",
        source: ~s([inputs: ["{mix,.formatter}.exs", "{config,lib,test}/**/*.{ex,exs}"]]\n)
      },
      %{
        module: nil,
        path: ".gitignore",
        source: "/_build/\n/deps/\n/doc/\nerl_crash.dump\n*.ez\n"
      },
      %{module: nil, path: "README.md", source: readme(ir, base, app, version, env_var, title)},
      %{module: nil, path: ".github/workflows/ci.yml", source: ci_workflow()}
    ] ++ regenerate_workflow(base, opts[:spec])
  end

  @setup_beam """
        - uses: actions/checkout@v4
        - uses: erlef/setup-beam@v1
          with:
            elixir-version: "1.18"
            otp-version: "27"
        - uses: actions/cache@v4
          with:
            path: |
              deps
              _build
            key: mix-${{ runner.os }}-${{ hashFiles('mix.lock') }}
            restore-keys: mix-${{ runner.os }}-
        - run: mix deps.get
  """

  defp ci_workflow do
    """
    # Generated by Infusion.
    name: CI

    on:
      push:
      pull_request:

    jobs:
      test:
        runs-on: ubuntu-latest
        steps:
    #{@setup_beam}      - run: mix compile --warnings-as-errors
          - run: if [ -f test/test_helper.exs ]; then mix test; fi
    """
  end

  # Only a spec at a URL can be fetched again.
  defp regenerate_workflow(base, spec) do
    if is_binary(spec) and String.starts_with?(spec, ["http://", "https://"]) do
      [
        %{
          module: nil,
          path: ".github/workflows/regenerate.yml",
          source: regenerate_source(base, spec)
        }
      ]
    else
      []
    end
  end

  defp regenerate_source(base, spec) do
    """
    # Generated by Infusion. Fetches the spec every day, regenerates the SDK,
    # and opens a pull request when anything changed. The pull request needs
    # "Allow GitHub Actions to create and approve pull requests" in the
    # repository's Settings > Actions > General.
    name: Regenerate

    on:
      schedule:
        - cron: "17 5 * * *"
      workflow_dispatch:

    permissions:
      contents: write
      pull-requests: write

    jobs:
      regenerate:
        runs-on: ubuntu-latest
        steps:
    #{@setup_beam}      - name: Regenerate from #{spec}
            run: mix infusion.gen --config infusion.exs | tee "$RUNNER_TEMP/infusion.log"
          - name: Compile
            run: mix compile --warnings-as-errors
          - name: Test
            run: if [ -f test/test_helper.exs ]; then mix test; fi
          - name: Describe the changes
            run: |
              {
                echo "Regenerating the #{base} SDK from its API spec changed it."
                echo
                echo "It compiles without warnings and its tests pass. Review the API changes below, then bump the version and the changelog before releasing."
                echo
                echo '```'
                cat "$RUNNER_TEMP/infusion.log"
                echo
                # Staged, so new and deleted files are counted too.
                git add -A
                git diff --cached --stat
                echo '```'
              } > "$RUNNER_TEMP/body.md"
          - uses: peter-evans/create-pull-request@v7
            with:
              branch: infusion/regenerate
              delete-branch: true
              commit-message: Regenerate from the API spec
              title: Regenerate from the API spec
              body-path: ${{ runner.temp }}/body.md
    """
  end

  defp client(ir, base, app, version, env_var, title, info, opts) do
    defaults =
      ([
         base_url: Operations.server_url(List.first(ir.servers)),
         api_key: if(ir.auth, do: env_key(env_var)),
         auth: ir.auth,
         user_agent: "#{app}/#{version} (Elixir; infusion_runtime)"
       ] ++ Infusion.Config.client_defaults(opts))
      |> Enum.reject(fn {_k, v} -> v == nil end)

    """
    defmodule #{base} do
      @moduledoc #{Source.doc(moduledoc(base, app, env_var, title, info, ir, opts))}

      @defaults #{lit(defaults)}

      @doc \"\"\"
      The settings for a call: the defaults, then `config :#{app}, ...`, then
      `opts`. See `Infusion.Runtime.Config` for every setting.
      \"\"\"
      @spec config(keyword) :: Infusion.Runtime.Config.t()
      def config(opts \\\\ []) do
        Infusion.Runtime.Config.new([@defaults, Application.get_all_env(#{inspect(app)}), opts])
      end

      @doc \"\"\"
      Calls an endpoint this SDK has no function for:

          #{base}.request(:get, "/some/path", %{"limit" => 10})

      `params` go into the query for GET and DELETE, into a JSON body otherwise.
      \"\"\"
      @spec request(atom, String.t(), map | keyword, keyword) ::
              {:ok, term} | {:error, Infusion.Runtime.Error.t()}
      def request(method, path, params \\\\ %{}, opts \\\\ []) do
        operation = %{
          id: nil,
          method: method,
          path: path,
          body: if(method in [:get, :head, :delete], do: nil, else: :json)
        }

        __request__(operation, [], params, opts)
      end

      @doc false
      def __request__(operation, path_args, params, opts) do
        Infusion.Runtime.Request.run(config(), operation, path_args, params, opts)
      end

      @doc false
      def __stream__(operation, path_args, params, opts) do
        Infusion.Runtime.Request.stream(config(), operation, path_args, params, opts)
      end

      @doc false
      def __paginate__(operation, path_args, params, opts) do
        Infusion.Runtime.Paginate.stream(config(), operation, path_args, params, opts)
      end

      @doc false
      def __watch__(operation, path_args, params, opts) do
        Infusion.Runtime.Watch.start_link(config(), operation, path_args, params, opts)
      end
    end
    """
    |> format()
  end

  # {:env, "VAR"}, or a pair for basic auth from two variables.
  defp env_key({user, password}), do: {{:env, user}, {:env, password}}
  defp env_key(var), do: {:env, var}

  defp env_text({user, password}), do: "`#{user}` and `#{password}`"
  defp env_text(var), do: "`#{var}`"

  defp key_example({_user, _password}), do: ~s({"user", "password"})
  defp key_example(_var), do: ~s("...")

  defp moduledoc(base, app, env_var, title, info, ir, opts) do
    description = String.trim(info["description"] || "")

    auth =
      if ir.auth,
        do: "The API key is read from #{env_text(env_var)}, or set it in your config:",
        else: "Settings go in your config:"

    """
    Elixir SDK for #{title}#{if info["version"], do: " (API version #{info["version"]})", else: ""}.

    #{description}

    ## Configuration

    #{auth}

        config :#{app}, api_key: #{key_example(env_var)}, max_retries: 3, timeout: 60_000

    #{path_settings_doc(app, opts)}

    Any setting can also be given to a single call, as the last argument:

        #{base}.SomeResource.some_call(params, timeout: 5_000)

    Generated by [Infusion](https://github.com/mandar1045/infusion).
    """
    |> String.replace(~r/\n{3,}/, "\n\n")
  end

  # Settings that fill a path parameter (Twilio's account SID).
  defp path_settings_doc(app, opts) do
    for {name, setting} <- Enum.sort(opts[:path_defaults] || %{}) do
      {setting, default} =
        case setting do
          {setting, default} -> {setting, default}
          setting -> {setting, nil}
        end

      from =
        case default do
          {:env, var} -> ", read from `#{var}` unless set"
          _ -> ""
        end

      "`#{inspect(setting)}` fills `{#{name}}` in every path#{from}: " <>
        "`config :#{app}, #{setting}: \"...\"`, or `#{setting}: \"...\"` on a single call."
    end
    |> Enum.join("\n\n")
  end

  defp mix_exs(base, app, version, deps, description, license, links, extras) do
    """
    defmodule #{base}.MixProject do
      use Mix.Project

      def project do
        [
          app: #{inspect(app)},
          version: #{inspect(version)},
          elixir: "~> 1.18",
          start_permanent: Mix.env() == :prod,
          deps: deps(),
          description: #{inspect(description)},
          package: [licenses: [#{inspect(license)}], links: #{inspect(links)}],
          docs: [main: "readme", extras: #{inspect(extras)}]
        ]
      end

      def application do
        [extra_applications: [:logger]]
      end

      defp deps do
        [
          #{Enum.join(deps, ",\n")},
          {:plug, "~> 1.14", only: :test},
          {:ex_doc, "~> 0.34", only: :dev, runtime: false}
        ]
      end
    end
    """
    |> format()
  end

  defp readme(ir, base, app, version, env_var, title) do
    """
    # #{base}

    Elixir SDK for #{title}, generated from its OpenAPI spec by
    [Infusion](https://github.com/mandar1045/infusion).

    ```elixir
    def deps do
      [{#{inspect(app)}, "~> #{version |> String.split(".") |> Enum.take(2) |> Enum.join(".")}"}]
    end
    ```

    #{if ir.auth, do: "Set #{env_text(env_var)}, or `config :#{app}, api_key: #{key_example(env_var)}`.", else: ""}

    Every call returns `{:ok, result}` or `{:error, %Infusion.Runtime.Error{}}`,
    and has a `!` variant that raises. Calls are retried on connection errors,
    429 and 5xx, as the official SDKs do.

    #{length(ir.operations)} operations, #{map_size(ir.schemas)} schemas.
    """
    |> String.replace(~r/\n{3,}/, "\n\n")
  end

  # The settings this SDK was generated with, so it can be regenerated from
  # its own directory: `mix infusion.gen --config infusion.exs`.
  defp infusion_exs(base, app, env_var, opts) do
    given = Keyword.take(opts, Infusion.Config.keys())

    settings =
      [name: base, spec: spec_path(opts[:spec], opts[:out]), out: ".", app: app, env_var: env_var]
      |> Keyword.merge(Keyword.drop(given, [:name, :spec, :out, :app, :env_var]))
      |> patches_path(opts[:out])
      |> Enum.reject(fn {_k, v} -> v == nil end)
      |> Enum.sort_by(fn {k, _} -> Enum.find_index(Infusion.Config.keys(), &(&1 == k)) end)

    """
    # How this SDK is generated. Regenerate it, from this directory, with
    #
    #     mix infusion.gen --config infusion.exs
    #
    # Every setting is described in Infusion.Config.
    #{lit(settings)}
    """
    |> format()
  end

  # A patches file next to the SDK's infusion.exs is found without saying so.
  defp patches_path(settings, out) do
    case settings[:patches] do
      path when is_binary(path) ->
        relative = spec_path(path, out)

        if relative == "infusion.patches.json",
          do: Keyword.delete(settings, :patches),
          else: Keyword.put(settings, :patches, relative)

      _ ->
        settings
    end
  end

  defp spec_path(nil, _out), do: nil

  defp spec_path(spec, out) do
    cond do
      String.starts_with?(spec, ["http://", "https://"]) -> spec
      out -> Path.relative_to(Path.expand(spec), Path.expand(out), force: true)
      true -> Path.expand(spec)
    end
  end

  defp lit(term), do: Source.lit(term)
  defp format(source), do: Source.format(source)
end
